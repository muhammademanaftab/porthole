import CoreGraphics
import Foundation
import PortholeCore

func wholeMacTests() {
    expect("whole mac: default mode is ask", WholeMac.mode(stored: nil, environment: [:]), .ask)
    expect("whole mac: stored always", WholeMac.mode(stored: "always", environment: [:]), .always)
    expect("whole mac: stored junk falls back to ask", WholeMac.mode(stored: "maybe", environment: [:]), .ask)
    expect("whole mac: env beats the stored setting", WholeMac.mode(stored: "always", environment: ["PORTHOLE_WHOLE_MAC": "OFF"]), .off)
    expect("whole mac: unknown env value is ignored", WholeMac.mode(stored: "off", environment: ["PORTHOLE_WHOLE_MAC": "yes"]), .off)

    let device = "0123456789abcdef"
    let paired = pairedIdentity(name: "Laptop", suffix: "abc", device: device)
    let password = WebRoutes.viewerIdentity(name: "Browser", suffix: "x1y")
    expect("whole mac: a paired identity is a paired viewer", WholeMac.viewer(paired), .paired(device: device))
    expect("whole mac: a password identity is a password viewer", WholeMac.viewer(password), .password(identity: password))
    expect("whole mac: the host and other identities are not viewers", WholeMac.viewer("host"), .other)
    expect("whole mac: a guest-style identity gets nothing", WholeMac.viewer("guest-abc"), .other)
    expect("whole mac: viewer name from a password identity", WholeMac.viewerName(password), "Browser")
    expect("whole mac: viewer name from a paired identity", WholeMac.viewerName(paired), "Laptop")
    check("whole mac: off offers nothing", !WholeMac.offered(mode: .off, viewer: .password(identity: password)))
    check("whole mac: ask offers to password viewers", WholeMac.offered(mode: .ask, viewer: .password(identity: password)))
    check("whole mac: never offered to others", !WholeMac.offered(mode: .always, viewer: .other))

    expect("whole mac: screen ids start high", WholeMac.windowID(screen: 0), 0xFFFF_FF00)
    expect("whole mac: out-of-range screen index has no id", WholeMac.windowID(screen: 16), nil)
    expect("whole mac: negative index has no id", WholeMac.windowID(screen: -1), nil)
    expect("whole mac: id round-trips to an index", WholeMac.screenIndex(0xFFFF_FF03), 3)
    check("whole mac: real window ids are not screens", !WholeMac.isScreen(12345) && !WholeMac.isScreen(0xFFFF_FEFF) && !WholeMac.isScreen(0xFFFF_FF10))
    check("whole mac: track names still work for screen ids", Message.windowID(fromTrackName: Message.trackName(for: 0xFFFF_FF01)) == 0xFFFF_FF01)

    let builtin = ScreenFacts(id: 1, frame: CGRect(x: 0, y: 0, width: 1512, height: 982), scale: 2, isMain: true, isBuiltin: true, vendor: 0x610)
    let left = ScreenFacts(id: 7, frame: CGRect(x: -1920, y: -200, width: 1920, height: 1080), scale: 1, isMain: false, isBuiltin: false, vendor: 0x10AC)
    let right = ScreenFacts(id: 5, frame: CGRect(x: 1512, y: 0, width: 2560, height: 1440), scale: 2, isMain: false, isBuiltin: false, vendor: 0x10AC)
    let stage = ScreenFacts(id: 9, frame: CGRect(x: 4072, y: 0, width: 1512, height: 982), scale: 2, isMain: false, isBuiltin: false, vendor: 0x504F, isStage: true)
    expect("whole mac: main first, then left to right, Stage left out", WholeMac.ordered([right, stage, left, builtin]).map(\.id), [1, 7, 5])
    let entries = WholeMac.entries([right, stage, left, builtin], matched: false)
    expect("whole mac: one card per display", entries.map(\.id), [0xFFFF_FF00, 0xFFFF_FF01, 0xFFFF_FF02])
    expect("whole mac: card titles", entries.map(\.title), ["Main Display", "Display 2", "Display 3"])
    check("whole mac: cards are marked as screens with the Whole Mac name", entries.allSatisfy { $0.screen == true && $0.app == "Whole Mac" && $0.bundle == nil })
    expect("whole mac: card size is the display's points", entries.map { CGSize(width: $0.w, height: $0.h) },
           [builtin.frame.size, left.frame.size, right.frame.size])
    expect("whole mac: a single display is the Main Display", WholeMac.entries([builtin], matched: false).map(\.title), ["Main Display"])
    expect("whole mac: target resolves the index against the same order", WholeMac.target(0xFFFF_FF01, screens: [right, stage, left, builtin])?.id, 7)
    expect("whole mac: a vanished display resolves to nothing", WholeMac.target(0xFFFF_FF05, screens: [builtin]), nil)
    expect("whole mac: a window id never resolves to a display", WholeMac.target(42, screens: [builtin]), nil)

    let stub = ScreenFacts(id: 2, frame: CGRect(x: 0, y: 0, width: 1920, height: 1080), scale: 1, isMain: true, isBuiltin: false, vendor: 0x756E_6B6E)
    check("whole mac: a MacBook does not need the screen match", !WholeMac.needsScreenMatch([builtin], environment: [:]))
    check("whole mac: a real monitor does not need the screen match", !WholeMac.needsScreenMatch([right], environment: [:]))
    check("whole mac: a headless stub needs the screen match", WholeMac.needsScreenMatch([stub], environment: [:]))
    check("whole mac: the Stage alone counts as headless", WholeMac.needsScreenMatch([stage], environment: [:]))
    check("whole mac: PORTHOLE_SCREEN_MATCH=0 turns it off", !WholeMac.needsScreenMatch([stub], environment: ["PORTHOLE_SCREEN_MATCH": "0"]))
    check("whole mac: PORTHOLE_SCREEN_MATCH=1 forces it", WholeMac.needsScreenMatch([builtin], environment: ["PORTHOLE_SCREEN_MATCH": "1"]))
    let matched = WholeMac.entries([stage], matched: true)
    expect("whole mac: matched shows one card for this Mac's screen", matched.map(\.title), ["This Mac's Screen"])
    expect("whole mac: matched card takes the Stage's size", matched.first.map { CGSize(width: $0.w, height: $0.h) }, stage.frame.size)

    expect("whole mac: centre of a display", WholeMac.inputPoint(nx: 0.5, ny: 0.5, screen: builtin.frame), CGPoint(x: 756, y: 491))
    expect("whole mac: corner of a display left of the main one", WholeMac.inputPoint(nx: 0, ny: 1, screen: left.frame), CGPoint(x: -1920, y: 880))
    expect("whole mac: points outside the picture clamp to the display", WholeMac.inputPoint(nx: 1.4, ny: -0.2, screen: right.frame), CGPoint(x: 1512 + 2560, y: 0))
    check("whole mac: keys, text, clicks and scrolling are injected", [Message.Kind.key, .text, .mouse, .scroll].allSatisfy(WholeMac.acceptsInput))
    check("whole mac: resize never reaches a display", !WholeMac.acceptsInput(.resize))
    expect("whole mac: native pixels for a Retina display", WholeMac.capturePixels(screen: builtin.frame, scale: 2, level: 2), CGSize(width: 3024, height: 1964))
    expect("whole mac: the ladder level caps the capture", WholeMac.capturePixels(screen: builtin.frame, scale: 2, level: 1), CGSize(width: 1512, height: 982))
    expect("whole mac: a 5K display is held to the capture limit", WholeMac.capturePixels(screen: CGRect(x: 0, y: 0, width: 2560, height: 1440), scale: 2, level: 2),
           capturePixelSize(points: CGSize(width: 2560, height: 1440), scale: 2))

    let pv: WholeMacViewer = .password(identity: password)
    var a = WholeMacApprovals(timeout: 18)
    expect("approval: off refuses", a.request(mode: .off, viewer: pv, now: 0), .refuse(WholeMacApprovals.offMessage))
    expect("approval: other viewers are refused even with always", a.request(mode: .always, viewer: .other, now: 0), .refuse(WholeMacApprovals.notAllowedMessage))
    expect("approval: always needs no question", a.request(mode: .always, viewer: pv, now: 0), .allow)
    expect("approval: ask asks the first time", a.request(mode: .ask, viewer: pv, now: 1), .ask(key: pv.approvalKey!))
    expect("approval: repeated opens wait for the same question", a.request(mode: .ask, viewer: pv, now: 3), .waiting)
    check("approval: an answer settles the question", a.answer(pv.approvalKey!, allow: true))
    check("approval: a second answer is ignored", !a.answer(pv.approvalKey!, allow: false))
    expect("approval: once allowed it is not asked again this session", a.request(mode: .ask, viewer: pv, now: 100), .allow)
    expect("approval: turning it off still refuses an allowed viewer", a.request(mode: .off, viewer: pv, now: 100), .refuse(WholeMacApprovals.offMessage))
    let other: WholeMacViewer = .paired(device: device)
    expect("approval: each viewer is asked separately", a.request(mode: .ask, viewer: other, now: 100), .ask(key: other.approvalKey!))
    _ = a.answer(other.approvalKey!, allow: false)
    expect("approval: a declined viewer is asked again next time", a.request(mode: .ask, viewer: other, now: 101), .ask(key: other.approvalKey!))
    expect("approval: nothing expires early", a.expire(now: 110), [])
    expect("approval: an unanswered question expires", a.expire(now: 119), [other.approvalKey!])
    check("approval: an expired question can't be answered", !a.answer(other.approvalKey!, allow: true))
    expect("approval: after expiry it asks again", a.request(mode: .ask, viewer: other, now: 120), .ask(key: other.approvalKey!))
    a.reset()
    expect("approval: a new host session asks again", a.request(mode: .ask, viewer: pv, now: 200), .ask(key: pv.approvalKey!))

    var t = WholeMacApprovals(timeout: 18)
    check("thumbnails: ask mode shows no picture before approval", !t.isApproved(mode: .ask, viewer: pv))
    check("thumbnails: always mode shows the picture", t.isApproved(mode: .always, viewer: pv))
    check("thumbnails: off never shows it", !t.isApproved(mode: .off, viewer: pv))
    check("thumbnails: other viewers never see it", !t.isApproved(mode: .always, viewer: .other))
    _ = t.request(mode: .ask, viewer: pv, now: 0)
    check("thumbnails: an unanswered question shows no picture", !t.isApproved(mode: .ask, viewer: pv))
    t.answer(pv.approvalKey!, allow: true)
    check("thumbnails: after Allow the picture is sent", t.isApproved(mode: .ask, viewer: pv))
    check("thumbnails: turning Whole Mac off hides it again", !t.isApproved(mode: .off, viewer: pv))
    _ = t.request(mode: .ask, viewer: other, now: 1)
    t.cancel(other.approvalKey!)
    check("approval: a withdrawn question can't be answered later", !t.answer(other.approvalKey!, allow: true))
    check("approval: and grants nothing", !t.isApproved(mode: .ask, viewer: other))

    check("start: off never starts, even approved and present", !WholeMac.mayStart(mode: .off, approved: true, viewerPresent: true))
    check("start: a viewer that left is never started", !WholeMac.mayStart(mode: .always, approved: true, viewerPresent: false))
    check("start: ask needs the approval", !WholeMac.mayStart(mode: .ask, approved: false, viewerPresent: true))
    check("start: ask with approval starts", WholeMac.mayStart(mode: .ask, approved: true, viewerPresent: true))
    check("start: always starts a present viewer", WholeMac.mayStart(mode: .always, approved: false, viewerPresent: true))
    check("input: no control once off", !WholeMac.mayControl(mode: .off) && WholeMac.mayControl(mode: .ask))
    expect("off: every live Whole Mac session ends, windows stay", WholeMac.sessionsToEnd(mode: .off, live: [42, 0xFFFF_FF01, 7, 0xFFFF_FF00]), [0xFFFF_FF00, 0xFFFF_FF01])
    expect("off: nothing ends while allowed", WholeMac.sessionsToEnd(mode: .ask, live: [0xFFFF_FF00]), [])

    let prompt = CGRect(x: 1100, y: 30, width: 360, height: 120)
    check("guard: a viewer click on the question is dropped", WholeMac.blocksInjectedClick(at: CGPoint(x: 1400, y: 130), guarded: [prompt]))
    check("guard: a click just outside its edge is dropped too", WholeMac.blocksInjectedClick(at: CGPoint(x: 1095, y: 26), guarded: [prompt]))
    check("guard: clicks elsewhere pass", !WholeMac.blocksInjectedClick(at: CGPoint(x: 500, y: 500), guarded: [prompt]))
    check("guard: with no question open everything passes", !WholeMac.blocksInjectedClick(at: CGPoint(x: 1400, y: 130), guarded: []))

    var q = WholeMacQueue()
    let k1 = pv.approvalKey!, k2 = other.approvalKey!
    check("queue: first request is queued", q.add(k1, WholeMacWaiter(id: 0xFFFF_FF00, who: password)))
    check("queue: the viewer's retries are not queued twice", !q.add(k1, WholeMacWaiter(id: 0xFFFF_FF00, who: password)))
    q.add(k1, WholeMacWaiter(id: 0xFFFF_FF01, who: password))
    q.add(k2, WholeMacWaiter(id: 0xFFFF_FF00, who: paired))
    expect("queue: a viewer leaving withdraws only its own question", q.drop(who: password), [k1])
    expect("queue: Allow for a viewer that left starts nothing", q.take(k1), [])
    expect("queue: the other viewer still waits", q.take(k2), [WholeMacWaiter(id: 0xFFFF_FF00, who: paired)])
    check("queue: empty after answering", q.isEmpty)
    q.add(k1, WholeMacWaiter(id: 0xFFFF_FF00, who: password))
    q.add(k2, WholeMacWaiter(id: 0xFFFF_FF00, who: paired))
    expect("queue: a room drop or Off clears every question", q.removeAll().keys.sorted(), [k1, k2].sorted())
    check("queue: and leaves nothing behind", q.isEmpty)
}
